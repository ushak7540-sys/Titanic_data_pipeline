# imports,constants,exceptions,load_data()

import pandas as pd
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

TARGET = "survived"
RANDOM_STATE = 42
REQUIRED_COLS = [
    "survived", "pclass", "sex", "age", "sibsp", "parch", "fare",
    "embarked", "class", "who", "adult_male", "deck",
    "embark_town", "alive", "alone",
]

class DataValidationError(Exception):
    """Raised when required columns are missing."""
    pass

def load_data():
    """Load the Titanic dataset from Seaborn."""
    return sns.load_dataset("titanic")

df = load_data()
print(df.shape)              # expect (891, 15)
print(df.isna().sum())       # age, deck, embarked, embark_town have NaNs
df.head()

# validate_data()
def validate_data(df):
    """Check that all required columns exist, else raise DataValidationError."""
    missing = set(REQUIRED_COLS) - set(df.columns)
    if missing:
        raise DataValidationError(f"Missing required columns: {sorted(missing)}")
    return df

# Test 1: should pass
df = validate_data(load_data())
print("Valid data OK:", df.shape)

# Test 2: should raise the error
try:
    validate_data(df.drop(columns=["age"]))
except DataValidationError as e:
    print("Caught:", e)

# clean_text()
def clean_text(df):
    """Normalize text columns: strip whitespace and lowercase."""
    df = df.copy()
    text_cols = df.select_dtypes(include=["object", "category"]).columns
    for col in text_cols:
        df[col] = df[col].astype("object").str.strip().str.lower()
    return df

df = clean_text(validate_data(load_data()))
print(df.select_dtypes(include="object").columns.tolist())
print(df["embarked"].unique())   # now lowercase: s, c, q (and nan)
print(df["class"].unique())      # first, second, third
print(df.isna().sum().sum())     # NaNs should be unchanged, not turned into "nan" text

# drop_useless()
def drop_useless(df):
    """Drop columns that leak the target, are mostly empty, or duplicate others."""
    cols_to_drop = [
        "alive",     # leaks target (same info as survived)
        "deck",      # ~77% missing
        "embarked",  # duplicate of embark_town
        "pclass",    # duplicate of class (we ordinal-encode class in Step 6)
    ]
    return df.drop(columns=cols_to_drop)

df = drop_useless(clean_text(validate_data(load_data())))
print(df.shape)              # expect (891, 11)
print(df.columns.tolist())

#Handle_missing()
def handle_missing(df):
    """Fill numeric NaNs with median, categorical NaNs with mode. Never touch the target."""
    df = df.copy()

    # Note: filling before the split leaks a little test info into train.
    # Done here to follow the spec; fitting on train only would be stricter.

    num_cols = df.select_dtypes(include="number").columns.drop(TARGET)
    for col in num_cols:
        df[col] = df[col].fillna(df[col].median())

    cat_cols = df.select_dtypes(include="object").columns
    for col in cat_cols:
        df[col] = df[col].fillna(df[col].mode()[0])

    return df

df = handle_missing(drop_useless(clean_text(validate_data(load_data()))))
print(df.isna().sum())          # all zeros
print(df.isna().sum().sum())    # expect 0
print(df["age"].median())       # expect 28.0
print(df["embark_town"].mode()[0])  # expect southampton

# encode_categoricals
def encode_categoricals(df):
    """Binary map + ordinal map + one-hot encode."""
    df = df.copy()

    # Binary
    df["sex"] = df["sex"].map({"male": 0, "female": 1})
    df["adult_male"] = df["adult_male"].astype(int)
    df["alone"] = df["alone"].astype(int)

    # Ordinal (order matters: third < second < first)
    df["class"] = df["class"].map({"third": 0, "second": 1, "first": 2})

    # One-hot (no natural order)
    df = pd.get_dummies(df, columns=["who", "embark_town"],
                        drop_first=True, dtype=int)
    return df

df = encode_categoricals(handle_missing(drop_useless(clean_text(validate_data(load_data())))))
print(df.shape)              # expect (891, 13)
print(df.columns.tolist())
print(df.dtypes)             # all numeric, no object
print(df.isna().sum().sum()) # expect 0

# split_data()
def split_data(df):
    """Stratified 80/20 train-test split."""
    X = df.drop(columns=[TARGET])
    y = df[TARGET]
    return train_test_split(
        X, y,
        test_size=0.2,
        stratify=y,
        random_state=RANDOM_STATE,
    )

df = encode_categoricals(handle_missing(drop_useless(clean_text(validate_data(load_data())))))
X_train, X_test, y_train, y_test = split_data(df)

print(X_train.shape, X_test.shape)   # expect (712, 12) (179, 12)
print(y_train.shape, y_test.shape)   # expect (712,) (179,)
print(round(y_train.mean(), 3), round(y_test.mean(), 3))  # both about 0.384

#scale_features()
def scale_features(X_train, X_test):
    """StandardScaler fit on train only; scale continuous columns."""
    X_train = X_train.copy()
    X_test = X_test.copy()
    cols = ["age", "fare", "sibsp", "parch"]

    scaler = StandardScaler()
    X_train[cols] = scaler.fit_transform(X_train[cols])  # fit on train only
    X_test[cols] = scaler.transform(X_test[cols])        # transform only

    return X_train, X_test, scaler

df = encode_categoricals(handle_missing(drop_useless(clean_text(validate_data(load_data())))))
X_train, X_test, y_train, y_test = split_data(df)
X_train_s, X_test_s, scaler = scale_features(X_train, X_test)

print(X_train_s[["age", "fare", "sibsp", "parch"]].mean().round(3))  # about 0
print(X_train_s[["age", "fare", "sibsp", "parch"]].std().round(3))   # about 1
print(X_test_s[["age", "fare", "sibsp", "parch"]].mean().round(3))   # close to 0, not exact
print(X_train_s.head())

#main()
def main():
    try:
        df = load_data()
        df = validate_data(df)
        df = clean_text(df)
        df = drop_useless(df)
        df = handle_missing(df)
        df = encode_categoricals(df)
        X_train, X_test, y_train, y_test = split_data(df)
        X_train, X_test, scaler = scale_features(X_train, X_test)

        print("Pipeline completed successfully")
        print("X_train:", X_train.shape, "| X_test:", X_test.shape)
        print("y_train:", y_train.shape, "| y_test:", y_test.shape)
        return X_train, X_test, y_train, y_test, scaler

    except DataValidationError as e:
        print(f"Validation failed: {e}")
    except Exception as e:
        print(f"Unexpected error: {e}")

if __name__ == "__main__":
    main()

X_train, X_test, y_train, y_test, scaler = main()

print("NaNs in train:", X_train.isna().sum().sum())       # 0
print("NaNs in test:", X_test.isna().sum().sum())         # 0
print("Non-numeric cols:", X_train.select_dtypes(exclude="number").columns.tolist())  # []
print("Survival ratio:", round(y_train.mean(), 3), round(y_test.mean(), 3))  # about 0.384 both
